"""Generate die_fold_atlas.h + layout.hlsl from the die-fold prototype.

die-fold's whole runtime is one per-pixel pass reading a flat parameter buffer,
plus a CPU bilinear sample of a 15x15 PARAMETER atlas (X = grain, Y = netness).
Both halves read their names, constants and hash salts from the prototype's
exported JSON, never from a hand-typed table: every sibling's shader drifted
from its Python in the INDICES, so neither side here retypes one. This script is
the HLSL twin of the prototype's `web/src/layout.ts` `wgslPreamble()`.

  die_fold_atlas.h  (C++, CPU only)  the 225 x 70 atlas, the 72 parameter
                    ranges, the pin, the path family table, ranges, defaults
                    and the six discovered presets, and the buffer layout.
  layout.hlsl       (shader)         the constants, the salts and the P_<NAME>
                    buffer indices `present.hlsl` reads through.

Run once and commit the output (no build-time python dependency):

    python3 effects/die_fold/gen_atlas.py [--src /path/to/die-fold/web/public]
"""

import argparse
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
# nano-modules-extras/effects/die_fold -> ../../../nano-fx-prototypes
DEFAULT_SRC = os.path.join(HERE, "..", "..", "..", "nano-fx-prototypes", "die-fold", "web", "public")

# The slots that are not scene parameters, in buffer order. The prototype's
# VIEW_SLOTS (layout.ts) plus `px_scale` (host::pxScale, so a capped preview
# resolves the same levels of the hierarchy as a full-res export).
VIEW_SLOTS = ["t", "surf_w", "surf_h", "probe", "cam_cell_x", "cam_cell_y",
              "cam_frac_x", "cam_frac_y", "seed", "px_scale"]

# Loop bounds, sizes and enum tags rather than measurements: emitted as int and,
# alongside, as <NAME>_F float (layout.ts INT_CONSTANTS).
INT_CONSTANTS = {
    "N_TRACK", "D_MAX", "RES_REF", "RUN_MAX", "PITCH_LO", "PITCH_HI",
    "N_KIND", "N_MOTIF", "N_LAYERS", "N_SLABS",
    "KIND_ARRAY", "KIND_ROWS", "KIND_LOGIC", "KIND_DPATH", "KIND_COMB",
    "KIND_MACRO", "KIND_MOTIF",
}


def f32(v):
    """A float literal that round-trips an f32 exactly."""
    s = f"{float(v):.9g}"
    if "." not in s and "e" not in s and "inf" not in s and "nan" not in s:
        s += ".0"
    return s


def cfloat(v):
    return f32(v) + "f"


def wrap(items, per=8, indent="  "):
    out = []
    for i in range(0, len(items), per):
        out.append(indent + ", ".join(items[i:i + per]) + ",")
    return "\n".join(out)


def gen_layout_hlsl(at, names):
    slot = {n: i for i, n in enumerate(VIEW_SLOTS)}
    for n in names:
        assert n not in slot, f"parameter {n} collides with a view slot"
        slot[n] = len(slot)
    size = len(slot)
    out = [
        "// GENERATED by gen_atlas.py from the die-fold prototype -- do not edit here.",
        "#ifndef DIE_FOLD_LAYOUT_HLSL",
        "#define DIE_FOLD_LAYOUT_HLSL",
        "",
        "static const float TAU = 6.283185307179586;",
        "",
        "// --- constants, read off the Python modules by build_scenes.py ---",
    ]
    for k, v in at["constants"].items():
        if k in INT_CONSTANTS:
            out.append(f"static const int {k} = {int(round(v))};")
            out.append(f"static const float {k}_F = {f32(round(v))};")
        else:
            out.append(f"static const float {k} = {f32(v)};")
    out += ["", "// --- hash salts. Two streams sharing one is an invisible bug. ---"]
    for k, v in at["salts"].items():
        out.append(f"static const uint {k} = {int(v)}u;")
    out += ["", "// --- parameter-buffer indices ---"]
    for k, v in slot.items():
        out.append(f"static const uint P_{k.upper()} = {v}u;")
    out.append(f"static const uint PRM_SIZE = {size}u;")
    out.append(f"static const uint PRM_VEC4 = {(size + 3) // 4}u;")
    kw = ", ".join(f"{slot[n]}u" for n in at["kind_w"])
    out += ["", "// The seven fabric weights, in `leaf._KIND_W` order.",
            f"static const uint KW[{len(at['kind_w'])}] = {{ {kw} }};", "", "#endif", ""]
    return "\n".join(out), slot, size


def gen_atlas_h(at, names, slot, size):
    G = int(at["grid"])
    fold = at["fold_names"]
    K = len(fold)
    macro = at["path_macro"]
    mkeys = list(macro.keys())
    assert list(at["path_defaults"].keys()) == mkeys
    fams = at["path_families"]
    presets = at["path_presets"]

    o = [
        "// GENERATED by gen_atlas.py from the die-fold prototype -- do not edit here.",
        "// The 15x15 parameter atlas (X = grain, Y = netness), the parameter ranges,",
        "// the path tables and the buffer layout. CPU only: nothing here reaches the",
        "// GPU but the 82 floats the CPU samples out of it each frame.",
        "#pragma once",
        "",
        "namespace die_fold {",
        "",
        f"constexpr int DF_GRID = {G};",
        f"constexpr int DF_NFOLD = {K};",
        f"constexpr int DF_NPARAM = {len(names)};",
        f"constexpr int DF_PRM_SIZE = {size};",
        f"constexpr int DF_PRM_FLOATS = {((size + 3) // 4) * 4};",
        f"constexpr int DF_ATLAS_SEED = {int(at['seed'])};",
        "",
        "// Buffer slots (view slots, then the 72 parameters in params.RANGES order).",
    ]
    for k, v in slot.items():
        o.append(f"constexpr int S_{k.upper()} = {v};")
    o += ["", "// Parameter index (0..71) -> its range, for the lever offsets.",
          f"static const float DF_PARAM_LO[{len(names)}] = {{",
          wrap([cfloat(at["ranges"][n][0]) for n in names]), "};",
          f"static const float DF_PARAM_HI[{len(names)}] = {{",
          wrap([cfloat(at["ranges"][n][1]) for n in names]), "};",
          "", "// Fold slot (0..69) -> buffer slot.",
          f"static const int DF_FOLD_SLOT[{K}] = {{",
          wrap([str(slot[n]) for n in fold], per=16), "};",
          "", "// The pinned view: `zoom` and `span_cells` are camera state, not folded."]
    for k, v in at["pin"].items():
        o.append(f"constexpr float DF_PIN_{k.upper()} = {cfloat(v)};")
    o += ["", f"// [G*G][K], row-major (gi*G + gj), row 0 at the BOTTOM of the pad.",
          f"static const float DF_CELLS[{G * G * K}] = {{"]
    for cell in at["cells"]:
        assert len(cell) == K
        o.append(wrap([cfloat(v) for v in cell], per=10))
    o += ["};", "",
          "// --- paths: families, knob ranges, defaults, the six discovered presets ---",
          f"constexpr int DF_NFAM = {len(fams)};"]
    for i, f in enumerate(fams):
        o.append(f"constexpr int FAM_{f.upper()} = {i};")
    o += ["", f"constexpr int DF_NMACRO = {len(mkeys)};"]
    for i, k in enumerate(mkeys):
        o.append(f"constexpr int M_{k.upper()} = {i};")
    o += [f"static const float DF_MACRO_LO[{len(mkeys)}] = {{",
          wrap([cfloat(macro[k][0]) for k in mkeys]), "};",
          f"static const float DF_MACRO_HI[{len(mkeys)}] = {{",
          wrap([cfloat(macro[k][1]) for k in mkeys]), "};",
          f"static const float DF_MACRO_DEFAULT[{len(mkeys)}] = {{",
          wrap([cfloat(at["path_defaults"][k]) for k in mkeys]), "};",
          "",
          f"constexpr int DF_NPRESET = {len(presets)};",
          f"static const char* const DF_PRESET_NAME[{len(presets)}] = {{",
          "  " + ", ".join(f'"{n}"' for n in presets) + ",", "};",
          f"static const int DF_PRESET_FAMILY[{len(presets)}] = {{",
          "  " + ", ".join(str(fams.index(p["family"])) for p in presets.values()) + ",", "};",
          f"static const float DF_PRESET[{len(presets)}][{len(mkeys)}] = {{"]
    for name, p in presets.items():
        o.append("  {")
        o.append(wrap([cfloat(p[k]) for k in mkeys], indent="    "))
        o.append("  },")
    o += ["};", "", "}  // namespace die_fold", ""]
    return "\n".join(o)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--src", default=DEFAULT_SRC,
                    help="die-fold/web/public (holds atlas.json)")
    args = ap.parse_args()
    with open(os.path.join(args.src, "atlas.json")) as fh:
        at = json.load(fh)
    names = at["names"]
    assert len(at["cells"]) == at["grid"] ** 2
    hlsl, slot, size = gen_layout_hlsl(at, names)
    with open(os.path.join(HERE, "layout.hlsl"), "w") as fh:
        fh.write(hlsl)
    with open(os.path.join(HERE, "die_fold_atlas.h"), "w") as fh:
        fh.write(gen_atlas_h(at, names, slot, size))
    print(f"wrote layout.hlsl ({size} slots) + die_fold_atlas.h "
          f"({at['grid']}x{at['grid']}x{len(at['fold_names'])})")


if __name__ == "__main__":
    main()
