"""Turn a Blender layout dump (blender_dump_layout.py) into layout_ref.h.

    python3 gen_layout_ref.py layout_ref.json ../layout_ref.h

The dump re-runs the poster scene's part_structure.py layout with its own RNG
and records every block's untilted rest cell, jut axis and distance, tip,
size and material, so Lantern's "Reference" layout is the scene's exactly.
"""

import json
import sys

src, dst = sys.argv[1], sys.argv[2]
d = json.load(open(src))
cell = d["cell"]


def f(v):
    s = f"{v:.6g}"
    if "." not in s and "e" not in s:
        s += ".0"
    return s + "f"


rows = []
for b in d["blocks"]:
    mat = 1 if b["material"] == "Stone" else 0
    if b["kind"] == "block":
        span = [max(1, round((s + cell * (1 - d["cube_fill"])) / cell)) for s in b["size"]]
        rows.append("  {0, %s, %s, %s, %s, %s, %s, {%s}, %d},  // block" % (
            "{" + ", ".join(f(v) for v in b["rest"]) + "}",
            "{" + ", ".join(f(v) for v in b["axis"]) + "}",
            f(b["jut"]),
            "{" + ", ".join(f(v) for v in b["rot"]) + "}",
            "{" + ", ".join(f(v) for v in b["size"]) + "}",
            "{0.f, 0.f, 0.f}",
            ", ".join(str(s) for s in span), mat))
    else:
        rows.append("  {1, %s, %s, %s, %s, %s, %s, {0, 0, 0}, %d},  // fragment" % (
            "{" + ", ".join(f(v) for v in b["pos"]) + "}",
            "{" + ", ".join(f(v) for v in b["vel"]) + "}",
            f(0.0),
            "{" + ", ".join(f(v) for v in b["rot"]) + "}",
            "{" + ", ".join(f(v) for v in b["size"]) + "}",
            "{" + ", ".join(f(v) for v in b["spin"]) + "}",
            mat))

out = f"""// Generated by tools/gen_layout_ref.py from tools/layout_ref.json — do not edit.
//
// The poster scene's block layout (blender/scripts/part_structure.py, SEED 21),
// in the structure's UNTILTED frame with the core at the origin (Blender
// axes: Z up). Blocks: rest cell centre, jut axis, jut distance, tip (XYZ
// euler, rad), size (m), span in cells. Fragments: position, drift per frame
// (in `axis`), tumble per frame (in `spin`).
#pragma once

namespace lantern {{

struct RefBlock {{
  int fragment;
  float rest[3];
  float axis[3];
  float jut;
  float rot[3];
  float size[3];
  float spin[3];
  int span[3];
  int stone;
}};

constexpr float kRefTiltDeg[3] = {{{", ".join(f(v) for v in d["tilt_deg"])}}};
constexpr int kRefCount = {len(rows)};
constexpr RefBlock kRefBlocks[kRefCount] = {{
{chr(10).join(rows)}
}};

}}  // namespace lantern
"""
open(dst, "w").write(out)
print("wrote", dst, len(rows), "blocks")
